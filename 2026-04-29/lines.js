export function prefixOf(speaker, { panic = false, finisher = false } = {}) {
  const pool = finisher ? PREFIX_FINISHER[speaker]
    : panic ? PREFIX_PANIC[speaker]
    : PREFIX_NORMAL[speaker];
  return pick(pool || []);
}

